<?php
/**
 * Shared design per page type ("template").
 *
 * Every page carries <body data-template="city"> (or home, about, service ...).
 * Admin → Templates stores design choices per type in data/templates.json and
 * writes them to styles/template-design.css as rules scoped to that attribute.
 *
 * Two levels, on purpose:
 *   - Template level (here): look and feel for every page of that type.
 *   - Page level (Edit page → Design & image): one section on one page.
 * A page-level choice always wins, because the template rules only apply to
 * sections that do not carry their own data-op-bg / data-op-ink / data-op-pad / data-op-align.
 */
require_once __DIR__ . '/_library.php';

const TPL_TYPES = [
    'home'      => ['Home page', 'The front page.'],
    'about'     => ['About page', ''],
    'contact'   => ['Contact page', ''],
    'work'      => ['Work page', ''],
    'services'  => ['Services overview', 'The page that lists all services.'],
    'service'   => ['Service pages', 'One page per service.'],
    'industry'  => ['Industry pages', 'One page per industry.'],
    'country'   => ['Country pages', 'One page per country.'],
    'city'      => ['City pages', 'One page per city.'],
    'combo'     => ['Industry in a city pages', 'For example dental marketing in Dubai.'],
    'locations' => ['Locations overview', 'The page that lists all countries and cities.'],
    'blog'      => ['Blog page', 'The page that lists all posts.'],
    'post'      => ['Blog posts', 'Every article.'],
    'legal'     => ['Legal and policy pages', 'Privacy, terms, accessibility, sitemap.'],
];
const TPL_PAD = ['sm' => 'Compact', 'md' => 'Normal', 'lg' => 'Spacious'];
const TPL_RADIUS = ['sharp' => 'Sharp corners', 'soft' => 'Soft corners (default look)', 'round' => 'Very round corners'];
const TPL_HEAD = ['sm' => 'Smaller', 'lg' => 'Larger'];

function tpl_file() { return DATA_DIR . '/templates.json'; }
function tpl_load() {
    if (!is_file(tpl_file())) return [];
    $d = json_decode((string) file_get_contents(tpl_file()), true);
    return is_array($d) ? $d : [];
}
function tpl_save(array $all) {
    // Keep the version before this save so it can be restored (an empty one if this is the first save).
    if (is_file(tpl_file())) @copy(tpl_file(), DATA_DIR . '/templates.prev.json');
    else @file_put_contents(DATA_DIR . '/templates.prev.json', '{}');
    $ok = file_put_contents(tpl_file(), json_encode($all, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES), LOCK_EX) !== false;
    return $ok && tpl_write_css($all);
}
function tpl_restore_previous() {
    $prev = DATA_DIR . '/templates.prev.json';
    if (!is_file($prev)) return false;
    $d = json_decode((string) file_get_contents($prev), true);
    return is_array($d) && tpl_save($d);
}

/** Keep only values the editor can produce. */
function tpl_clean(array $in) {
    $out = [];
    $hex = fn($v) => sec_valid_hex($v);
    $enum = fn($v, $allowed) => in_array($v, $allowed, true) ? $v : '';
    $out['bg'] = $hex($in['bg'] ?? '');
    $out['accent'] = $hex($in['accent'] ?? '');
    $out['pad'] = $enum($in['pad'] ?? '', array_keys(TPL_PAD));
    $out['radius'] = $enum($in['radius'] ?? '', array_keys(TPL_RADIUS));
    $out['head_align'] = $enum($in['head_align'] ?? '', ['left', 'center']);
    $out['h_size'] = $enum($in['h_size'] ?? '', array_keys(TPL_HEAD));
    $out['sections'] = [];
    foreach ((array) ($in['sections'] ?? []) as $key => $s) {
        if (!is_string($key) || !preg_match('/^[a-z0-9-]{1,40}$/', $key) || !is_array($s)) continue;
        $row = ['bg' => $hex($s['bg'] ?? ''), 'ink' => $hex($s['ink'] ?? ''),
                'pad' => $enum($s['pad'] ?? '', array_keys(TPL_PAD)), 'align' => $enum($s['align'] ?? '', ['left', 'center'])];
        if (array_filter($row)) $out['sections'][$key] = $row;
    }
    return array_filter($out, fn($v) => $v !== '' && $v !== []);
}

function tpl_pad_value($p) { return ['sm' => 'var(--s-5)', 'md' => 'var(--s-6)', 'lg' => 'var(--s-8)'][$p] ?? ''; }

/** The generated stylesheet. */
function tpl_css(array $all = null) {
    $all = $all ?? tpl_load();
    $css = "/* Generated by Admin → Templates. Do not edit by hand. */\n";
    $text = ':is(h1, h2, h3, h4, h5, p, li, summary, dt, dd, blockquote, .kicker, .eyebrow)';
    foreach ($all as $type => $s) {
        if (!isset(TPL_TYPES[$type]) || !is_array($s)) continue;
        $b = 'body[data-template="' . $type . '"]';
        $vars = '';
        if (!empty($s['accent'])) $vars .= "--blue:{$s['accent']};--blue-deep:{$s['accent']};";
        if (!empty($s['bg'])) $vars .= "--ap-bg:{$s['bg']};";
        if (($s['radius'] ?? '') === 'sharp') $vars .= '--r-sm:3px;--r-md:5px;--r-lg:8px;--r-xl:10px;';
        if (($s['radius'] ?? '') === 'round') $vars .= '--r-sm:14px;--r-md:20px;--r-lg:30px;--r-xl:38px;';
        if ($vars !== '' || !empty($s['bg'])) $css .= "$b{" . $vars . (!empty($s['bg']) ? "background:{$s['bg']};" : '') . "}\n";
        if (!empty($s['pad'])) $css .= "$b section:not(.hero):not([data-op-pad]){padding-block:" . tpl_pad_value($s['pad']) . "}\n";
        if (($s['head_align'] ?? '') === 'center') $css .= "$b .section-head{text-align:center;margin-inline:auto}$b .section-head p{margin-inline:auto}\n";
        if (($s['head_align'] ?? '') === 'left') $css .= "$b .section-head,$b .section-head.center{text-align:left;margin-inline:0}$b .section-head p,$b .section-head.center p{margin-inline:0}\n";
        if (($s['h_size'] ?? '') === 'sm') $css .= "$b .hero h1{font-size:clamp(1.6rem,5vw,2.5rem)!important}$b .section-head h2{font-size:clamp(1.35rem,3vw,1.9rem)!important}\n";
        if (($s['h_size'] ?? '') === 'lg') $css .= "$b .hero h1{font-size:clamp(2.1rem,7vw,4.4rem)!important}$b .section-head h2{font-size:clamp(1.75rem,4.2vw,3.1rem)!important}\n";
        foreach ((array) ($s['sections'] ?? []) as $key => $r) {
            $sel = $b . ' section[data-op-key="' . $key . '"]';
            if (!empty($r['bg'])) $css .= "$sel:not([data-op-bg]){background:{$r['bg']}}\n";
            if (!empty($r['ink'])) $css .= "$sel:not([data-op-ink]) $text{color:{$r['ink']}}\n";
            if (!empty($r['pad'])) $css .= "$sel:not([data-op-pad]){padding-block:" . tpl_pad_value($r['pad']) . "}\n";
            if (!empty($r['align'])) $css .= "$sel:not([data-op-align]){text-align:{$r['align']}}\n";
        }
    }
    return $css;
}
function tpl_write_css(array $all) {
    return file_put_contents(SITE_ROOT . '/styles/template-design.css', tpl_css($all)) !== false;
}

/* ---------- Which pages belong to a template ---------- */

/** [file => title] of live pages of this type. */
function tpl_pages($type) {
    $out = [];
    foreach (glob(SITE_ROOT . '/*.html') ?: [] as $f) {
        $h = (string) file_get_contents($f);
        if (!preg_match('/<body[^>]*\sdata-template="' . preg_quote($type, '/') . '"/i', $h)) continue;
        $out[basename($f)] = preg_replace('/\s*\|\s*OrcaPulse\s*$/i', '', parse_title($h)) ?: basename($f);
    }
    return $out;
}
function tpl_counts() {
    $c = [];
    foreach (glob(SITE_ROOT . '/*.html') ?: [] as $f) {
        $t = page_type_of($f, (string) file_get_contents($f));
        $c[$t] = ($c[$t] ?? 0) + 1;
    }
    return $c;
}
/** Section keys used by pages of this type. */
function tpl_keys($type) {
    $keys = [];
    foreach (tpl_pages($type) as $file => $_) {
        if (preg_match_all('/<section\b[^>]*\sdata-op-key="([a-z0-9-]+)"/i', (string) file_get_contents(SITE_ROOT . '/' . $file), $m)) {
            foreach ($m[1] as $k) if ($k !== 'custom') $keys[$k] = true;
        }
    }
    return array_keys($keys);
}
/** Pages of this type with page-level colour, spacing or alignment set on a section. */
function tpl_override_pages($type) {
    $out = [];
    foreach (tpl_pages($type) as $file => $title) {
        if (preg_match('/<section\b[^>]*\sdata-op-(bg|ink|pad|align)="/i', (string) file_get_contents(SITE_ROOT . '/' . $file))) $out[$file] = $title;
    }
    return $out;
}
/** Remove page-level colour, spacing and alignment from every section of every page of this type. */
function tpl_clear_overrides($type) {
    $n = 0;
    $strip = function ($html) {
        return preg_replace_callback(SECTION_RE, function ($m) {
            $a = $m[1];
            foreach (['data-op-bg', 'data-op-ink', 'data-op-pad', 'data-op-align'] as $k) $a = sec_attr_set($a, $k, '');
            $a = sec_style_set($a, '--op-bg', '');
            $a = sec_style_set($a, '--op-ink', '');
            return '<section' . $a . '>' . $m[2] . '</section>';
        }, $html);
    };
    foreach (array_keys(tpl_pages($type)) as $file) {
        $live = SITE_ROOT . '/' . $file;
        $html = (string) file_get_contents($live);
        $new = $strip($html);
        if ($new !== $html && page_save($live, $new)) $n++;
        if (page_has_pending($file)) {
            $p = pending_path($file);
            file_put_contents($p, $strip((string) file_get_contents($p)));
        }
    }
    return $n;
}
