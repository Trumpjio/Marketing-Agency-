function validate_upload($file) {
    if (!$file || ($file['error'] ?? -1) !== UPLOAD_ERR_OK) return ['ok'=>false,'error'=>'Upload failed.'];
    if (($file['size'] ?? 0) > 10*1024*1024) return ['ok'=>false,'error'=>'File is larger than 10 MB.'];
    $ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));
    $allowedExt = ['jpg','jpeg','png','gif','webp','svg'];
    if (!in_array($ext,$allowedExt,true)) return ['ok'=>false,'error'=>'Only JPG, PNG, WebP, GIF or SVG allowed.'];
    $finfo = function_exists('finfo_open') ? finfo_open(FILEINFO_MIME_TYPE) : null;
    $mime = $finfo ? finfo_file($finfo,$file['tmp_name']) : (mime_content_type($file['tmp_name']) ?: '');
    if ($finfo) finfo_close($finfo);
    $okMimes = ['image/jpeg','image/png','image/gif','image/webp','image/svg+xml','text/plain'];
    if (!in_array($mime,$okMimes,true)) return ['ok'=>false,'error'=>'That file does not look like a real image (detected: ' . h($mime) . ').'];
    if ($ext === 'svg') {
        $svg = file_get_contents($file['tmp_name']);
        if (preg_match('/<\s*script/i',$svg) || preg_match('/on\w+\s*=/i',$svg) || stripos($svg,'javascript:') !== false) return ['ok'=>false,'error'=>'SVG contains script content. Export the SVG without scripts and try again.'];
    }
    return ['ok'=>true,'ext'=>$ext];
}
