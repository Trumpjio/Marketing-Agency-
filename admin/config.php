function rate_limit($bucket, $maxAttempts=10, $windowSec=900) {
    $ip = $_SERVER['REMOTE_ADDR'] ?? 'unknown';
    $file = DATA_DIR . '/.rate_' . preg_replace('/[^a-z0-9_]/', '', $bucket) . '.json';
    $now = time();
    $data = file_exists($file) ? (json_decode((string)file_get_contents($file), true) ?: []) : [];
    foreach ($data as $k=>$hits) {
        $data[$k] = array_values(array_filter($hits, fn($t) => $t > $now - $windowSec));
        if (!$data[$k]) unset($data[$k]);
    }
    $data[$ip] = $data[$ip] ?? [];
    if (count($data[$ip]) >= $maxAttempts) { file_put_contents($file, json_encode($data), LOCK_EX); return false; }
    $data[$ip][] = $now;
    file_put_contents($file, json_encode($data), LOCK_EX);
    @chmod($file, 0600);
    return true;
}
function rate_limit_clear($bucket) {
    $ip = $_SERVER['REMOTE_ADDR'] ?? 'unknown';
    $file = DATA_DIR . '/.rate_' . preg_replace('/[^a-z0-9_]/', '', $bucket) . '.json';
    if (!file_exists($file)) return;
    $data = json_decode((string)file_get_contents($file), true) ?: [];
    unset($data[$ip]);
    file_put_contents($file, json_encode($data), LOCK_EX);
}
